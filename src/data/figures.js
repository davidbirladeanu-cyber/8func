export function calculateFigureSimilarity(userScores, userAxisScores, figure) {
  if (!figure) return 50;

  // 1. 4-Axis Spectrum Mean Absolute Difference (Direct Ground Truth)
  let axisDiff = 0;
  let axisCount = 0;

  if (userAxisScores && figure.axes) {
    // E / I Axis Difference
    const uI = userAxisScores.EI ? (userAxisScores.EI.roundB ?? userAxisScores.EI.pctB ?? 50) : 50;
    const fI = figure.axes.I ?? 50;
    axisDiff += Math.abs(uI - fI);
    axisCount++;

    // N / S Axis Difference
    const uS = userAxisScores.NS ? (userAxisScores.NS.roundB ?? userAxisScores.NS.pctB ?? 50) : 50;
    const fS = figure.axes.S ?? 50;
    axisDiff += Math.abs(uS - fS);
    axisCount++;

    // T / F Axis Difference
    const uF = userAxisScores.TF ? (userAxisScores.TF.roundB ?? userAxisScores.TF.pctB ?? 50) : 50;
    const fF = figure.axes.F ?? 50;
    axisDiff += Math.abs(uF - fF);
    axisCount++;

    // J / P Axis Difference
    const uP = userAxisScores.JP ? (userAxisScores.JP.roundB ?? userAxisScores.JP.pctB ?? 50) : 50;
    const fP = figure.axes.P ?? 50;
    axisDiff += Math.abs(uP - fP);
    axisCount++;
  }

  const avgAxisDiff = axisCount > 0 ? (axisDiff / axisCount) : 30;
  const axisSimilarity = Math.max(0, Math.min(100, 100 - avgAxisDiff));

  // 2. Cognitive Function Vector Difference
  let funcDiff = 0;
  if (userScores && figure.scores) {
    FUNCTIONS.forEach(f => {
      const u = userScores[f] ?? 50;
      const fig = figure.scores[f] ?? 50;
      funcDiff += Math.abs(u - fig);
    });
  }
  const avgFuncDiff = funcDiff / FUNCTIONS.length;
  const funcSimilarity = Math.max(0, Math.min(100, 100 - avgFuncDiff));

  // 3. Integrated Similarity: 70% direct 4-axis scores + 30% cognitive functions
  const finalScore = Math.round(0.70 * axisSimilarity + 0.30 * funcSimilarity);
  return Math.max(0, Math.min(100, finalScore));
}

/**
 * Returns Top 10 Similar and Top 10 Opposite Figures for the user
 *
 * @param {Object} userScores - User's 8 cognitive function percentages
 * @param {Object} userAxisScores - User's 4 MBTI axis scores
 * @returns {{ similar: Array, opposite: Array, all: Array }}
 */
export function getRankedFigures(userScores, userAxisScores) {
  const list = NOTABLE_FIGURES.map(fig => {
    const similarity = calculateFigureSimilarity(userScores, userAxisScores, fig);
    const cleanRole = fig.role ? fig.role.replace(/\s*·\s*[A-Z]{4}\s*$/i, "").trim() : (fig.profession || "");
    return {
      ...fig,
      role: cleanRole,
      similarity,
      oppositeScore: 100 - similarity
    };
  });

  const similar = [...list].sort((a, b) => b.similarity - a.similarity).slice(0, 10);
  const opposite = [...list].sort((a, b) => a.similarity - b.similarity).slice(0, 10);

  return { similar, opposite, all: list };
}

